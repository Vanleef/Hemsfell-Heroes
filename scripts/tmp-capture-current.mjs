import fs from "node:fs";
const [port="9225",out,width="1678",height="943"]=process.argv.slice(2);
const tabs=await fetch(`http://127.0.0.1:${port}/json`).then(r=>r.json());
const tab=tabs.find(item=>item.type==="page");
if(!tab)throw new Error("No page target");
const ws=new WebSocket(tab.webSocketDebuggerUrl);
await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject});
let id=0;const pending=new Map();
ws.onmessage=event=>{const msg=JSON.parse(event.data);if(!pending.has(msg.id))return;const task=pending.get(msg.id);pending.delete(msg.id);msg.error?task.reject(new Error(msg.error.message)):task.resolve(msg.result)};
const send=(method,params={})=>new Promise((resolve,reject)=>{const key=++id;pending.set(key,{resolve,reject});ws.send(JSON.stringify({id:key,method,params}))});
await send("Page.enable");
await send("Emulation.setDeviceMetricsOverride",{width:Number(width),height:Number(height),deviceScaleFactor:1,mobile:false});
await send("Page.reload",{ignoreCache:true});
await new Promise(resolve=>setTimeout(resolve,6000));
const state=await send("Runtime.evaluate",{expression:`({game:!!document.querySelector('.hs-board'),slots:[...document.querySelectorAll('.slot-type-icon')].slice(0,3).map(e=>e.textContent),emptyCue:document.body.innerText.includes('SEM EFEITOS ATIVOS'),overlay:!!document.querySelector('[data-nextjs-dialog]')})`,returnByValue:true});
const shot=await send("Page.captureScreenshot",{format:"png",captureBeyondViewport:false});
fs.writeFileSync(out,Buffer.from(shot.data,"base64"));
console.log(JSON.stringify(state.result.value));
ws.close();
