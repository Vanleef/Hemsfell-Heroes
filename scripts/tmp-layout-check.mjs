import fs from "node:fs";
const [port="9225",out,width="1678",height="943"]=process.argv.slice(2);
const tabs=await fetch(`http://127.0.0.1:${port}/json`).then(r=>r.json());
const tab=tabs.find(item=>item.type==="page");
if(!tab)throw new Error("No page target");
const ws=new WebSocket(tab.webSocketDebuggerUrl);
await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject});
let id=0;const pending=new Map();
ws.onmessage=event=>{const msg=JSON.parse(event.data);if(!pending.has(msg.id))return;const task=pending.get(msg.id);pending.delete(msg.id);msg.error?task.reject(new Error(msg.error.message)):task.resolve(msg.result)};
const send=(method,params={})=>new Promise((resolve,reject)=>{const key=++id;pending.set(key,{resolve,reject});ws.send(JSON.stringify({id:key,method,params}))});
const evaluate=expression=>send("Runtime.evaluate",{expression,awaitPromise:true,returnByValue:true});
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
await send("Page.enable");
await send("Emulation.setDeviceMetricsOverride",{width:Number(width),height:Number(height),deviceScaleFactor:1,mobile:false});
await send("Page.navigate",{url:"http://127.0.0.1:3000"});
for(let attempt=0;attempt<25;attempt++){
 await sleep(800);
 const ready=await evaluate(`[...document.querySelectorAll('button')].some(b=>/jogar contra ia/i.test(b.textContent))`);
 if(ready.result.value)break;
}
await evaluate(`[...document.querySelectorAll('button')].find(b=>/jogar contra ia/i.test(b.textContent))?.click()`);
await sleep(900);
await evaluate(`[...document.querySelectorAll('button')].find(b=>/iniciar partida/i.test(b.textContent))?.click()`);
await sleep(3500);
await evaluate(`[...document.querySelectorAll('button')].find(b=>/expandir energia/i.test(b.textContent))?.click()`);
await sleep(3500);
const state=await evaluate(`({game:!!document.querySelector('.hs-board'),slotIcons:[...document.querySelectorAll('.slot-type-icon')].slice(0,3).map(e=>getComputedStyle(e,'::before').webkitMaskImage),emptyCue:document.body.innerText.includes('SEM EFEITOS ATIVOS'),geometry:[...document.querySelectorAll('.player-hero,.hero-command-bar,.hero-evolution,.level-button,.player-hand,.paired-field,.field-slot')].slice(0,28).map(e=>{const r=e.getBoundingClientRect();return {c:e.className,x:Math.round(r.x),y:Math.round(r.y),w:Math.round(r.width),h:Math.round(r.height)}}),overlay:!!document.querySelector('[data-nextjs-dialog]')})`);
const shot=await send("Page.captureScreenshot",{format:"png",captureBeyondViewport:false});
fs.writeFileSync(out,Buffer.from(shot.data,"base64"));
console.log(JSON.stringify(state.result.value));ws.close();
